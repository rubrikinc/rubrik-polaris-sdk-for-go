// client is the common Polaris client used for tests. By reusing the same
// client we reduce the risk of hitting rate limits when access tokens are
// created.
var client *polaris.Client

func TestMain(m *testing.M) {
	if testsetup.BoolEnvSet("TEST_INTEGRATION") {
		// Load configuration and create client. Usually resolved using the
		// environment variable RUBRIK_POLARIS_SERVICEACCOUNT_FILE.
		polAccount, err := polaris.DefaultServiceAccount(true)
		if err != nil {
			fmt.Printf("failed to get default service account: %v\n", err)
			os.Exit(1)
		}

		// The integration tests defaults the log level to INFO. Note that
		// RUBRIK_POLARIS_LOGLEVEL can be used to override this.
		logger := log.NewStandardLogger()
		logger.SetLogLevel(log.Info)
		if err := polaris.SetLogLevelFromEnv(logger); err != nil {
			fmt.Printf("failed to get log level from env: %v\n", err)
			os.Exit(1)
		}

		client, err = polaris.NewClientWithLogger(polAccount, logger)
		if err != nil {
			fmt.Printf("failed to create polaris client: %v\n", err)
			os.Exit(1)
		}

		version, err := client.GQL.DeploymentVersion(context.Background())
		if err != nil {
			fmt.Printf("failed to get deployment version: %v\n", err)
			os.Exit(1)
		}
		logger.Printf(log.Info, "Polaris version: %s", version)
	}

	os.Exit(m.Run())
}

// TestKeyManagers verifies that the SDK can read key managers from a real RSC
// instance. The test is read only, it does not register a key manager, since
// doing so requires a cloud account onboarded with the
// CLOUD_NATIVE_UEM_KEY_MANAGEMENT feature.
//
// Note that kmsInstances is gated by the UNIFIED_ENCRYPTION_MANAGEMENT_ENABLED
// feature flag. Without it RSC rejects the query.
func TestKeyManagers(t *testing.T) {
	if !testsetup.BoolEnvSet("TEST_INTEGRATION") {
		t.Skipf("skipping due to env TEST_INTEGRATION not set")
	}

	keyManagers, err := Wrap(client).KeyManagers(context.Background(), kms.ListKeyManagerFilter{})
	if err != nil {
		t.Fatal(err)
	}

	for _, keyManager := range keyManagers {
		if keyManager.Name == "" {
			t.Errorf("key manager %v has no name", keyManager.KeyVaultInfo.ID)
		}
		if keyManager.Type == "" {
			t.Errorf("key manager %q has no KMS type", keyManager.Name)
		}

		// Every KMS type except a KMIP server is identified by a UUID.
		if keyManager.Type != kms.TypeKMIPServer && keyManager.KeyVaultInfo.ID == uuid.Nil {
			t.Errorf("key manager %q has no ID", keyManager.Name)
		}
	}
}
